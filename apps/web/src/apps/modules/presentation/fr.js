// ─────────────────────────────────────────────────────────────────────────
// POURQUOI CE FICHIER EXISTE
//
// `pptx-react-viewer` annonce le français dans son catalogue de langues,
// mais n'embarque que les chaînes anglaises : passer `defaultLocale="fr"`
// change le réglage sans changer un seul libellé. Le ruban s'affichait donc
// en anglais dans un OS entièrement français.
//
// Le moteur ne crée pas son instance i18next — il appelle `useTranslation()`
// et lit celle de l'OS. Il suffit donc d'enregistrer nos propres chaînes
// par-dessus les siennes.
//
// CE QUI EST TRADUIT, ET CE QUI NE L'EST PAS
//
// Le catalogue complet compte 3 356 entrées, dont l'essentiel est constitué
// de noms d'animations, de types de graphiques et de réglages fins qu'on
// n'atteint qu'en descendant loin dans les panneaux. Traduire ces 3 356
// entrées à la main serait long, et surtout fragile : une faute de frappe
// dans une clé passe inaperçue jusqu'au jour où quelqu'un ouvre le panneau
// concerné.
//
// Ce fichier couvre donc ce qu'on voit **en travaillant** : les onglets du
// ruban et leurs boutons, la barre d'outils, la barre d'état, le menu
// Fichier, le menu contextuel, le mode diaporama et le mode présentateur.
// Le reste reste en anglais et se traduira au fil de l'usage — le repli est
// **par clé**, pas par langue : une entrée absente d'ici prend simplement
// sa version anglaise, rien ne casse.
//
// Les clés sont plates et pointées (« pptx.ribbon.home ») : c'est la forme
// qu'attend la bibliothèque. Les `{{variables}}` doivent être conservées
// telles quelles, elles sont remplacées à l'affichage.
// ─────────────────────────────────────────────────────────────────────────

